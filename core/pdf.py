"""
ApexForge PDF generation — ReportLab helpers.

Every public function returns an HttpResponse with Content-Type application/pdf.
"""
import io
from datetime import date

from django.http import HttpResponse
from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_RIGHT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import cm
from reportlab.platypus import (
    Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle, KeepTogether,
)
# Note: Spacer is only used in story (not as table cells — ReportLab rejects that)

# ── Palette ───────────────────────────────────────────────────────────────────
GREEN        = colors.HexColor("#059669")
GREEN_DARK   = colors.HexColor("#047857")
GREEN_LIGHT  = colors.HexColor("#ecfdf5")
GREEN_ACCENT = colors.HexColor("#a7f3d0")
GRAY_900     = colors.HexColor("#111827")
GRAY_700     = colors.HexColor("#374151")
GRAY_500     = colors.HexColor("#6b7280")
GRAY_200     = colors.HexColor("#e5e7eb")
GRAY_50      = colors.HexColor("#f9fafb")
RED_BG       = colors.HexColor("#fee2e2")
RED_FG       = colors.HexColor("#991b1b")
AMBER_BG     = colors.HexColor("#fef3c7")
AMBER_FG     = colors.HexColor("#92400e")
BLUE_BG      = colors.HexColor("#dbeafe")
BLUE_FG      = colors.HexColor("#1e40af")
WHITE        = colors.white

PAGE_W, PAGE_H = A4
MARGIN  = 1.8 * cm
BODY_W  = PAGE_W - 2 * MARGIN          # ≈ 17.9 cm
BANNER_H = 1.7 * cm
TOP_MARGIN = MARGIN + BANNER_H + 0.5 * cm   # content starts below banner
BOT_MARGIN = MARGIN + 0.6 * cm             # content ends above footer


# ── Paragraph style factory ───────────────────────────────────────────────────
def _p(name, font="Helvetica", size=9, color=GRAY_900, align=TA_LEFT,
       leading=None, bold=False):
    return ParagraphStyle(
        name,
        fontName="Helvetica-Bold" if bold else font,
        fontSize=size,
        textColor=color,
        alignment=align,
        leading=leading or size * 1.35,
    )


def _styles():
    return {
        "SectionHead": _p("SH",  bold=True, size=9,  color=GREEN_DARK),
        "KV_Key":      _p("KVK", bold=True, size=9,  color=GREEN_DARK),
        "KV_Val":      _p("KVV", size=9,  color=GRAY_900),
        "TH":          _p("TH",  bold=True, size=8,  color=WHITE,   align=TA_CENTER),
        "TD":          _p("TD",  size=8,  color=GRAY_900),
        "TD_C":        _p("TDC", size=8,  color=GRAY_900, align=TA_CENTER),
        "Small":       _p("Sm",  size=8,  color=GRAY_500, leading=12),
        "Center":      _p("Ctr", size=8,  color=GRAY_500, align=TA_CENTER),
        "Bold":        _p("Bld", bold=True, size=9, color=GRAY_900),
        "GreenBold":   _p("GB",  bold=True, size=10, color=GREEN_DARK),
        "Sub":         _p("Sub", size=9, color=GRAY_500),
        # Payroll amounts
        "Amount":      _p("Amt", bold=True, size=10, color=GRAY_900, align=TA_RIGHT),
        "AmountNet":   _p("AN",  bold=True, size=11, color=GREEN_DARK, align=TA_RIGHT),
    }


# ── Canvas page decorator (banner + footer on every page) ─────────────────────
def _page_decorator(canvas, doc, title, subtitle):
    canvas.saveState()

    lx = MARGIN
    w  = BODY_W

    # ── Banner ─────────────────────────────────────────────────────────────
    by = PAGE_H - MARGIN - BANNER_H
    canvas.setFillColor(GREEN)
    canvas.roundRect(lx, by, w, BANNER_H, 6, fill=1, stroke=0)

    # accent stripe along the bottom of the banner
    canvas.setFillColor(GREEN_DARK)
    canvas.rect(lx, by, w, 3, fill=1, stroke=0)

    # Left: brand name
    canvas.setFont("Helvetica-Bold", 17)
    canvas.setFillColor(WHITE)
    canvas.drawString(lx + 14, by + BANNER_H * 0.55, "ApexForge")
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(GREEN_ACCENT)
    canvas.drawString(lx + 14, by + BANNER_H * 0.2, "Sports Management Platform")

    # Right: document title + subtitle
    canvas.setFont("Helvetica-Bold", 12)
    canvas.setFillColor(WHITE)
    canvas.drawRightString(lx + w - 14, by + BANNER_H * 0.55, title)
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(GREEN_ACCENT)
    canvas.drawRightString(lx + w - 14, by + BANNER_H * 0.2, subtitle)

    # ── Footer ──────────────────────────────────────────────────────────────
    fy = MARGIN - 0.3 * cm
    fh = 0.55 * cm
    canvas.setFillColor(GRAY_50)
    canvas.rect(lx, fy, w, fh, fill=1, stroke=0)
    canvas.setStrokeColor(GRAY_200)
    canvas.setLineWidth(0.5)
    canvas.line(lx, fy + fh, lx + w, fy + fh)

    canvas.setFont("Helvetica", 7.5)
    canvas.setFillColor(GRAY_500)
    today = date.today().strftime("%d %B %Y")
    canvas.drawString(lx + 6, fy + 0.15 * cm, f"Generated by ApexForge  |  {today}")
    canvas.setFont("Helvetica-Bold", 7.5)
    canvas.drawRightString(lx + w - 6, fy + 0.15 * cm, f"Page {doc.page}")

    canvas.restoreState()


# ── Section heading ───────────────────────────────────────────────────────────
def _section(story, s, text):
    tbl = Table(
        [[Paragraph(text.upper(), s["SectionHead"])]],
        colWidths=[BODY_W],
    )
    tbl.setStyle(TableStyle([
        ("BACKGROUND",    (0, 0), (-1, -1), GREEN_LIGHT),
        ("LINEBEFORE",    (0, 0), (0, -1),  3, GREEN),
        ("LINEBELOW",     (0, 0), (-1, -1), 0.5, GRAY_200),
        ("LEFTPADDING",   (0, 0), (-1, -1), 10),
        ("RIGHTPADDING",  (0, 0), (-1, -1), 8),
        ("TOPPADDING",    (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(Spacer(1, 0.3 * cm))
    story.append(tbl)
    story.append(Spacer(1, 0.15 * cm))


# ── KV info table ─────────────────────────────────────────────────────────────
def _kv_table(data, key_w=5 * cm, total_w=None):
    total_w = total_w or BODY_W
    val_w   = total_w - key_w
    rows = [
        [Paragraph(str(k), _p("k", bold=True, size=9, color=GREEN_DARK)),
         Paragraph(str(v), _p("v", size=9, color=GRAY_900))]
        for k, v in data
    ]
    tbl = Table(rows, colWidths=[key_w, val_w])
    tbl.setStyle(TableStyle([
        ("BACKGROUND",     (0, 0), (0, -1),  GREEN_LIGHT),
        ("ROWBACKGROUNDS", (1, 0), (1, -1),  [WHITE, GRAY_50]),
        ("GRID",           (0, 0), (-1, -1), 0.4, GRAY_200),
        ("LEFTPADDING",    (0, 0), (-1, -1), 10),
        ("RIGHTPADDING",   (0, 0), (-1, -1), 8),
        ("TOPPADDING",     (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING",  (0, 0), (-1, -1), 6),
        ("VALIGN",         (0, 0), (-1, -1), "MIDDLE"),
        ("LINEBELOW",      (0, -1), (-1, -1), 1, GREEN),
    ]))
    return tbl


# ── Data table ────────────────────────────────────────────────────────────────
def _data_table(headers, rows, col_widths=None, center_cols=None):
    center_cols = center_cols or []
    hdr_style = _p("_th", bold=True, size=8, color=WHITE,   align=TA_CENTER)
    bod_style  = _p("_td", size=8,  color=GRAY_900)
    bod_c      = _p("_tdc", size=8, color=GRAY_900, align=TA_CENTER)

    data = [[Paragraph(h, hdr_style) for h in headers]]
    for row in rows:
        data.append([
            Paragraph(str(c), bod_c if i in center_cols else bod_style)
            for i, c in enumerate(row)
        ])

    tbl = Table(data, colWidths=col_widths, repeatRows=1)
    tbl.setStyle(TableStyle([
        ("BACKGROUND",     (0, 0),  (-1, 0),  GREEN),
        ("TOPPADDING",     (0, 0),  (-1, 0),  7),
        ("BOTTOMPADDING",  (0, 0),  (-1, 0),  7),
        ("ROWBACKGROUNDS", (0, 1),  (-1, -1), [WHITE, GRAY_50]),
        ("GRID",           (0, 0),  (-1, -1), 0.4, GRAY_200),
        ("LEFTPADDING",    (0, 0),  (-1, -1), 8),
        ("RIGHTPADDING",   (0, 0),  (-1, -1), 8),
        ("TOPPADDING",     (0, 1),  (-1, -1), 5),
        ("BOTTOMPADDING",  (0, 1),  (-1, -1), 5),
        ("VALIGN",         (0, 0),  (-1, -1), "MIDDLE"),
        ("LINEBELOW",      (0, -1), (-1, -1), 1, GREEN),
    ]))
    return tbl


# ── Stat badge (colored background cell) ─────────────────────────────────────
def _badge_cell(tbl, col, row, bg, fg):
    tbl.setStyle(TableStyle([
        ("BACKGROUND", (col, row), (col, row), bg),
        ("TEXTCOLOR",  (col, row), (col, row), fg),
        ("FONTNAME",   (col, row), (col, row), "Helvetica-Bold"),
    ]))


def _pdf_response(filename):
    response = HttpResponse(content_type="application/pdf")
    response["Content-Disposition"] = f'attachment; filename="{filename}"'
    return response


