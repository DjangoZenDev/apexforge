# 2. Contract PDF
# ═══════════════════════════════════════════════════════════════════════════════

def contract_pdf(contract):
    fname = f"contract_{contract.pk}_{contract.title.replace(' ', '_')}.pdf"
    response = _pdf_response(fname)
    buf = io.BytesIO()

    doc_title    = contract.title
    doc_subtitle = f"Contract  |  {contract.get_contract_type_display()}"

    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=MARGIN, rightMargin=MARGIN,
        topMargin=TOP_MARGIN, bottomMargin=BOT_MARGIN,
    )
    s = _styles()
    story = []

    # ── Contract details ──────────────────────────────────────────────────────
    _section(story, s, "Contract Details")
    days_rem = getattr(contract, "days_remaining", None)
    status_display = contract.get_status_display()
    story.append(_kv_table([
        ("Contract Type",  contract.get_contract_type_display()),
        ("Status",         status_display),
        ("Party",          getattr(contract, "party_name", "—") or "—"),
        ("Start Date",     str(contract.start_date)),
        ("End Date",       str(contract.end_date)),
        ("Value",          f"€ {contract.value:,.2f}" if contract.value else "—"),
        ("Days Remaining", f"{days_rem} days" if days_rem and days_rem > 0 else "Expired"),
        ("Signed",         "Yes" if contract.signed_date else "No"),
        ("Signed Date",    str(contract.signed_date) if contract.signed_date else "—"),
    ]))

    # ── Notes ─────────────────────────────────────────────────────────────────
    if contract.notes:
        _section(story, s, "Notes")
        story.append(Paragraph(contract.notes, s["Small"]))

    # ── Clauses ───────────────────────────────────────────────────────────────
    clauses = contract.clauses.all()
    if clauses:
        _section(story, s, "Contract Clauses")
        rows = [
            [c.get_clause_type_display(), c.title,
             c.description[:90] + ("…" if len(c.description) > 90 else "")]
            for c in clauses
        ]
        story.append(_data_table(
            ["Type", "Title", "Description"],
            rows,
            col_widths=[4 * cm, 4.5 * cm, 9.4 * cm],
        ))

    # ── Signature block ───────────────────────────────────────────────────────
    story.append(Spacer(1, 1.2 * cm))
    _section(story, s, "Signatures")
    story.append(Spacer(1, 0.8 * cm))
    sig = Table(
        [
            ["Authorised Signatory", "", "Witness / Counterparty"],
            [" ", "", " "],
            [" ", "", " "],
            ["_________________________", "", "_________________________"],
            ["Name & Title", "", "Name & Title"],
            [f"Date: {'_' * 20}", "", f"Date: {'_' * 20}"],
        ],
        colWidths=[7.5 * cm, 2.9 * cm, 7.5 * cm],
    )
    sig.setStyle(TableStyle([
        ("FONTSIZE",      (0, 0), (-1, -1), 9),
        ("FONTNAME",      (0, 0), (-1, 0),  "Helvetica-Bold"),
        ("TEXTCOLOR",     (0, 0), (-1, 0),  GREEN_DARK),
        ("TEXTCOLOR",     (0, 1), (-1, -1), GRAY_500),
        ("TOPPADDING",    (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LINEBELOW",     (0, 2), (0, 2),   0.75, GRAY_500),
        ("LINEBELOW",     (2, 2), (2, 2),   0.75, GRAY_500),
    ]))
    story.append(sig)

    cb = lambda c, d: _page_decorator(c, d, doc_title, doc_subtitle)
    doc.build(story, onFirstPage=cb, onLaterPages=cb)
    response.write(buf.getvalue())
    return response


