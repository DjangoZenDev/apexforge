# 3. Payroll Slip PDF
# ═══════════════════════════════════════════════════════════════════════════════

def payroll_slip_pdf(payroll):
    name = payroll.staff_member.user.get_full_name()
    fname = f"payroll_{payroll.pk}_{name.replace(' ', '_')}.pdf"
    response = _pdf_response(fname)
    buf = io.BytesIO()

    if getattr(payroll, "period_start", None):
        period = (f"{payroll.period_start.strftime('%d %b')} – "
                  f"{payroll.period_end.strftime('%d %b %Y')}")
    else:
        period = "—"

    doc_title    = "Payroll Slip"
    doc_subtitle = f"{name}  |  {period}"

    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=MARGIN, rightMargin=MARGIN,
        topMargin=TOP_MARGIN, bottomMargin=BOT_MARGIN,
    )
    s = _styles()
    story = []

    # ── Employee info ─────────────────────────────────────────────────────────
    _section(story, s, "Employee Information")
    half = (BODY_W - 0.3 * cm) / 2
    kw   = 3.6 * cm

    left_tbl = _kv_table([
        ("Employee",   name),
        ("Job Title",  payroll.staff_member.job_title or "—"),
        ("Department", str(payroll.staff_member.department)
                       if payroll.staff_member.department else "—"),
    ], key_w=kw, total_w=half)

    right_tbl = _kv_table([
        ("Period",  period),
        ("Status",  "Paid" if getattr(payroll, "is_paid", False) else "Pending"),
        ("Notes",   payroll.notes or "—"),
    ], key_w=kw, total_w=half)

    grid = Table(
        [[left_tbl, "", right_tbl]],
        colWidths=[half, 0.3 * cm, half],
    )
    grid.setStyle(TableStyle([
        ("VALIGN",        (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING",   (1, 0), (1, -1), 0),
        ("RIGHTPADDING",  (1, 0), (1, -1), 0),
        ("TOPPADDING",    (1, 0), (1, -1), 0),
        ("BOTTOMPADDING", (1, 0), (1, -1), 0),
    ]))
    story.append(grid)

    # ── Earnings & deductions ─────────────────────────────────────────────────
    _section(story, s, "Earnings & Deductions")

    earn_rows = [
        # label, description, amount style, amount
        ("Gross Salary",  "Base remuneration",               "normal", payroll.gross_salary),
        ("Bonuses",       "Additional performance bonuses",  "normal", payroll.bonuses),
        ("Deductions",    "Tax, insurance & other",          "deduct", payroll.deductions),
    ]

    tbl_data = [
        [Paragraph("Description",   _p("_", bold=True, size=9, color=WHITE)),
         Paragraph("Details",       _p("_", bold=True, size=9, color=WHITE)),
         Paragraph("Amount",        _p("_", bold=True, size=9, color=WHITE, align=TA_RIGHT))],
    ]
    for label, detail, kind, amount in earn_rows:
        sign   = "-€" if kind == "deduct" else " €"
        fg     = RED_FG if kind == "deduct" else GRAY_900
        tbl_data.append([
            Paragraph(label,  _p("_", bold=True,  size=9,  color=GRAY_700)),
            Paragraph(detail, _p("_", size=9, color=GRAY_500)),
            Paragraph(f"{sign}{amount:,.2f}", _p("_", bold=True, size=9, color=fg, align=TA_RIGHT)),
        ])

    # Net row
    tbl_data.append([
        Paragraph("NET SALARY", _p("_", bold=True, size=11, color=GREEN_DARK)),
        Paragraph("", _p("_", size=9, color=WHITE)),
        Paragraph(f"€ {payroll.net_salary:,.2f}",
                  _p("_", bold=True, size=11, color=GREEN_DARK, align=TA_RIGHT)),
    ])

    earn_tbl = Table(tbl_data, colWidths=[5.5 * cm, 8.5 * cm, 3.9 * cm])
    earn_tbl.setStyle(TableStyle([
        # Header
        ("BACKGROUND",    (0, 0), (-1, 0),  GREEN),
        ("TOPPADDING",    (0, 0), (-1, 0),  8),
        ("BOTTOMPADDING", (0, 0), (-1, 0),  8),
        # Body rows
        ("ROWBACKGROUNDS",(0, 1), (-1, -2), [WHITE, GRAY_50]),
        ("GRID",          (0, 0), (-1, -2), 0.4, GRAY_200),
        ("LEFTPADDING",   (0, 0), (-1, -1), 10),
        ("RIGHTPADDING",  (0, 0), (-1, -1), 10),
        ("TOPPADDING",    (0, 1), (-1, -2), 7),
        ("BOTTOMPADDING", (0, 1), (-1, -2), 7),
        ("VALIGN",        (0, 0), (-1, -1), "MIDDLE"),
        # Net salary row
        ("BACKGROUND",    (0, -1), (-1, -1), GREEN_LIGHT),
        ("LINEABOVE",     (0, -1), (-1, -1), 1.5, GREEN),
        ("LINEBELOW",     (0, -1), (-1, -1), 1.5, GREEN),
        ("TOPPADDING",    (0, -1), (-1, -1), 10),
        ("BOTTOMPADDING", (0, -1), (-1, -1), 10),
    ]))
    story.append(earn_tbl)

    # ── Official notice ───────────────────────────────────────────────────────
    story.append(Spacer(1, 0.8 * cm))
