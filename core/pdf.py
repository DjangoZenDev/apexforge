# 1. Player Profile PDF
# ═══════════════════════════════════════════════════════════════════════════════

def player_profile_pdf(player):
    fname = f"player_{player.pk}_{player.full_name.replace(' ', '_')}.pdf"
    response = _pdf_response(fname)
    buf = io.BytesIO()

    doc_title    = player.full_name
    doc_subtitle = f"Player Profile  |  {player.get_sport_display()}"

    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=MARGIN, rightMargin=MARGIN,
        topMargin=TOP_MARGIN, bottomMargin=BOT_MARGIN,
    )
    s = _styles()
    story = []

    # ── Bio (2-column grid) ──────────────────────────────────────────────────
    _section(story, s, "Player Information")
    dob  = player.date_of_birth
    half = (BODY_W - 0.3 * cm) / 2
    kw   = 3.6 * cm

    left_tbl  = _kv_table([
        ("Full Name",   player.full_name),
        ("Position",    player.position or "—"),
        ("Sport",       player.get_sport_display()),
        ("Nationality", player.nationality or "—"),
    ], key_w=kw, total_w=half)

    right_tbl = _kv_table([
        ("Date of Birth", str(dob) if dob else "—"),
        ("Status",        player.get_status_display()),
        ("Height",        f"{player.height_cm} cm" if player.height_cm else "—"),
        ("Weight",        f"{player.weight_kg} kg" if player.weight_kg else "—"),
    ], key_w=kw, total_w=half)

    grid = Table(
        [[left_tbl, "", right_tbl]],
        colWidths=[half, 0.3 * cm, half],
    )
    grid.setStyle(TableStyle([
        ("VALIGN",        (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING",   (1, 0), (1, -1), 0),
        ("RIGHTPADDING",  (1, 0), (1, -1), 0),
        ("TOPPADDING",    (1, 0), (1, -1), 0),
        ("BOTTOMPADDING", (1, 0), (1, -1), 0),
    ]))
    story.append(grid)

    # ── Current team ─────────────────────────────────────────────────────────
    roster = player.rosters.select_related("team", "season").filter(is_active=True).first()
    if roster:
        _section(story, s, "Current Team")
        story.append(KeepTogether(_kv_table([
            ("Team",     roster.team.name),
            ("Season",   str(roster.season) if roster.season else "—"),
            ("Jersey",   f"#{roster.jersey_number}" if roster.jersey_number else "—"),
            ("Position", roster.position or "—"),
            ("Captain",  "Yes" if roster.is_captain else "No"),
        ])))

    # ── Season stats ──────────────────────────────────────────────────────────
    stats = player.stats.select_related("season", "team").order_by("-season__start_date")[:6]
    if stats:
        _section(story, s, "Season Statistics")
        rows = [[
            str(st.season) if st.season else "—",
            st.team.name if st.team else "—",
            str(st.goals),
            str(st.assists),
            str(st.appearances),
            str(st.yellow_cards),
            str(st.red_cards),
        ] for st in stats]

        tbl = _data_table(
            ["Season", "Team", "Goals", "Assists", "Apps", "Yellow", "Red"],
            rows,
            col_widths=[3.2*cm, 4.4*cm, 1.9*cm, 2*cm, 1.9*cm, 2.2*cm, 2.3*cm],
            center_cols=[2, 3, 4, 5, 6],
        )
        for i, st in enumerate(stats, 1):
            if st.yellow_cards:
                _badge_cell(tbl, 5, i, AMBER_BG, AMBER_FG)
            if st.red_cards:
                _badge_cell(tbl, 6, i, RED_BG, RED_FG)
            if st.goals >= 10:
                _badge_cell(tbl, 2, i, GREEN_LIGHT, GREEN_DARK)

        story.append(tbl)

    # ── Injury history ────────────────────────────────────────────────────────
    injuries = player.injuries.order_by("-injury_date")[:5]
    if injuries:
        _section(story, s, "Injury History")
        sev_colors = {
            "minor":    (colors.HexColor("#dcfce7"), colors.HexColor("#166534")),
            "moderate": (AMBER_BG, AMBER_FG),
            "severe":   (RED_BG,   RED_FG),
        }
        rows = [[
            str(inj.injury_date),
            inj.injury_type,
            inj.body_part or "—",
            inj.get_severity_display(),
            str(inj.expected_return) if inj.expected_return else "—",
        ] for inj in injuries]

        tbl = _data_table(
            ["Date", "Type", "Body Part", "Severity", "Expected Return"],
            rows,
            col_widths=[2.8*cm, 4.2*cm, 3.5*cm, 3.2*cm, 4.2*cm],
            center_cols=[0, 3, 4],
        )
        for i, inj in enumerate(injuries, 1):
            bg, fg = sev_colors.get(inj.severity, (WHITE, GRAY_900))
            tbl.setStyle(TableStyle([
                ("BACKGROUND", (3, i), (3, i), bg),
                ("TEXTCOLOR",  (3, i), (3, i), fg),
                ("FONTNAME",   (3, i), (3, i), "Helvetica-Bold"),
            ]))
        story.append(tbl)

    cb = lambda c, d: _page_decorator(c, d, doc_title, doc_subtitle)
    doc.build(story, onFirstPage=cb, onLaterPages=cb)
    response.write(buf.getvalue())
    return response


